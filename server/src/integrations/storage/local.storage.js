import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve, sep } from 'node:path';
import { createCipher } from '../../utils/crypto.js';

const KEY_PATTERN = /^[a-z0-9][a-z0-9/_.-]{8,200}$/;

/**
 * Private object storage on the local filesystem, encrypted at rest.
 *
 * Interface (shared with future S3-compatible drivers):
 *   put(key, buffer)  get(key) -> Buffer  delete(key)
 *
 * - Files sit outside any web root and are only served through the
 *   authenticated, signed download endpoint.
 * - Contents are encrypted with AES-256-GCM (ENCRYPTION_KEY), so a copied disk
 *   or backup does not expose identity documents.
 * - Keys are generated by the server (never from user input) and validated
 *   against path traversal.
 */
export function createLocalStorage({ baseDir, encryptionKey }) {
  const root = resolve(baseDir);
  const cipher = createCipher(encryptionKey);

  function pathFor(key) {
    if (!KEY_PATTERN.test(key) || key.includes('..')) throw new Error('Invalid storage key');
    const full = resolve(join(root, key));
    if (!full.startsWith(root + sep)) throw new Error('Storage key escapes the storage root');
    return full;
  }

  return {
    driver: 'local',
    async put(key, buffer) {
      const full = pathFor(key);
      await mkdir(dirname(full), { recursive: true });
      // Base64 before encrypting keeps the cipher helper's text interface. Overhead is about 33%.
      await writeFile(full, cipher.encrypt(buffer.toString('base64')), { flag: 'wx', mode: 0o600 });
    },
    async get(key) {
      const payload = await readFile(pathFor(key), 'utf8');
      return Buffer.from(cipher.decrypt(payload), 'base64');
    },
    async delete(key) {
      await rm(pathFor(key), { force: true });
    },
  };
}
